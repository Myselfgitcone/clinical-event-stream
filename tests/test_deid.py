# ---- properties of the mechanism -------------------------------------------


def test_pseudonyms_depend_on_the_salt():
    a = Deidentifier("salt-a", REFERENCE).pseudonym("x")
    b = Deidentifier("salt-b", REFERENCE).pseudonym("x")
    assert a != b and a == Deidentifier("salt-a", REFERENCE).pseudonym("x")


def test_shift_is_deterministic_bounded_and_never_zero():
    d = Deidentifier("s", REFERENCE)
    shifts = {d.shift_days(f"patient-{i}") for i in range(2000)}
    assert 0 not in shifts
    assert min(shifts) >= -MAX_SHIFT_DAYS and max(shifts) <= MAX_SHIFT_DAYS
    assert len(shifts) > 500  # spread, not clustered
    assert d.shift_days("p") == Deidentifier("s", REFERENCE).shift_days("p")


def test_ages_over_89_are_banded_and_lose_their_birth_year(deid, contracts):
    old = {**fhir.flatten_patient(PATIENT), "birth_date": date(1930, 1, 1), "_cohort_id": "c1"}
    out = deid.deidentify(contracts["patient"], old)
    assert out["age_band"] == "90+" and out["birth_year"] is None and out["age_over_89"] is True


@pytest.mark.parametrize(
    ("age", "band"),
    [
        (0, "0-17"),
        (17, "0-17"),
        (18, "18-34"),
        (49, "35-49"),
        (64, "50-64"),
        (79, "65-79"),
        (89, "80-89"),
        (90, "90+"),
        (104, "90+"),
    ],
)
def test_age_bands(age, band):
    assert age_band(age) == band


def test_zip3_truncates_and_zeroes_restricted_prefixes():
    assert zip3("65101") == "651"
    assert zip3("65101-1234") == "651"
    assert zip3("03601") == "000"  # low-population prefix per HHS
    assert zip3("1234") is None and zip3(None) is None


def test_empty_salt_is_refused():
    with pytest.raises(ValueError):
        Deidentifier("", REFERENCE)


def test_code_system_uris_are_not_swept(deid, contracts):
    """The URL sweep once replaced every `http://loinc.org` with [removed]; the
    audit count (sweeps == rows) exposed it. Only fields marked free_text are swept."""
    row = fhir.flatten_observation(
        {
            "resourceType": "Observation",
            "id": "o1",
            "status": "final",
            "code": {"coding": [{"system": "http://loinc.org", "code": "4548-4", "display": "HbA1c see http://x.y"}]},
            "subject": {"reference": "urn:uuid:p1"},
            "effectiveDateTime": "2020-01-01T00:00:00Z",
            "valueQuantity": {"value": 6.1, "unit": "%"},
        }
    )[0]
    out = deid.deidentify(contracts["observation"], {**row, "_cohort_id": "c1"})
    assert out["code_system"] == "http://loinc.org"
    assert out["display"] == "HbA1c see [removed]"
    assert not any(f.free_text for c in contracts.values() for f in c.fields if f.name in ("code_system", "code"))
