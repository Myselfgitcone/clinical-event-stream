def _text(row) -> str:
    return json.dumps(row, default=str)


# ---- the eighteen classes --------------------------------------------------


def test_01_names(silver_patient, silver_encounter):
    t = _text(silver_patient) + _text(silver_encounter)
    for v in ("Hegmann834", "Darron84", "Florentino8", "Oldname999", "Shery223", "Jacobs452", "Mr."):
        assert v not in t


def test_02_geography_below_state(silver_patient):
    t = _text(silver_patient)
    for v in ("Kerluke", "Jefferson City", "Rolla", "65101", "38.5767", "-92.1735"):
        assert v not in t
    assert silver_patient["postal_code"] == "651"
    assert silver_patient["state"] == "MO" and silver_patient["birthplace_state"] == "Missouri"


def test_03_dates_shifted_and_birth_reduced_to_year(deid, silver_patient, silver_encounter):
    assert "1990-03-05" not in _text(silver_patient)
    assert "birth_date" not in silver_patient
    assert silver_patient["birth_year"] in (1989, 1990, 1991)
    assert silver_patient["age_band"] == "35-49"
    shift = deid.shift_days(PATIENT["id"])
    assert shift != 0 and -MAX_SHIFT_DAYS <= shift <= MAX_SHIFT_DAYS
    start = silver_encounter["period_start"]
    assert start == fhir.parse_datetime("2020-05-01T09:00:00-05:00") + __import__("datetime").timedelta(days=shift)
    # the interval inside the record is preserved exactly
    assert (silver_encounter["period_end"] - start).total_seconds() == 1800


